def สร้างตารางกระแสเงินสด(
    ทางเลือก: ทางเลือกผิวทาง,
    ระยะวิเคราะห์: int,
    อัตราคิดลด: float,
    รวมมูลค่าซาก: bool = True
) -> pd.DataFrame:
    """
    สร้างตารางกระแสเงินสดรายปีสำหรับทางเลือกผิวทาง
    
    Parameters:
        ทางเลือก: ข้อมูลทางเลือกผิวทาง
        ระยะวิเคราะห์: ระยะเวลาวิเคราะห์ (ปี)
        อัตราคิดลด: อัตราคิดลดรายปี
        รวมมูลค่าซาก: รวมการคำนวณมูลค่าซากหรือไม่
    
    Returns:
        DataFrame แสดงกระแสเงินสดรายปี
    """
    รายการ = []
    พื้นที่ = ทางเลือก.พื้นที่
    
    # ปีที่ 0: ต้นทุนก่อสร้างเริ่มต้น
    ต้นทุนเริ่มต้น = ทางเลือก.ต้นทุนก่อสร้าง * พื้นที่
    รายการ.append({
        'ปี': 0,
        'กิจกรรม': 'ก่อสร้างเริ่มต้น',
        'ประเภท': 'ก่อสร้าง',
        'ต้นทุนตามปี': ต้นทุนเริ่มต้น,
        'ตัวคูณ_PW': 1.0,
        'มูลค่าปัจจุบัน': ต้นทุนเริ่มต้น
    })
    
    # กิจกรรมบำรุงรักษา
    for บำรุง in ทางเลือก.แผนบำรุงรักษา:
        if บำรุง.ความถี่ > 0:
            # บำรุงรักษาแบบเป็นรอบ
            ปี = บำรุง.ปีเริ่มต้น
            while ปี <= ระยะวิเคราะห์:
                ต้นทุน = บำรุง.ต้นทุนต่อหน่วย * พื้นที่
                pwf = (1 + อัตราคิดลด) ** (-ปี)
                รายการ.append({
                    'ปี': ปี,
                    'กิจกรรม': บำรุง.ชื่อกิจกรรม,
                    'ประเภท': 'บำรุงรักษา',
                    'ต้นทุนตามปี': ต้นทุน,
                    'ตัวคูณ_PW': pwf,
                    'มูลค่าปัจจุบัน': ต้นทุน * pwf
                })
                ปี += บำรุง.ความถี่
        else:
            # บำรุงรักษาครั้งเดียว
            if บำรุง.ปีเริ่มต้น <= ระยะวิเคราะห์:
                ต้นทุน = บำรุง.ต้นทุนต่อหน่วย * พื้นที่
                pwf = (1 + อัตราคิดลด) ** (-บำรุง.ปีเริ่มต้น)
                รายการ.append({
                    'ปี': บำรุง.ปีเริ่มต้น,
                    'กิจกรรม': บำรุง.ชื่อกิจกรรม,
                    'ประเภท': 'บำรุงรักษา',
                    'ต้นทุนตามปี': ต้นทุน,
                    'ตัวคูณ_PW': pwf,
                    'มูลค่าปัจจุบัน': ต้นทุน * pwf
                })
    
    # กิจกรรมฟื้นฟูสภาพ
    ต้นทุนฟื้นฟูสุดท้าย = ทางเลือก.ต้นทุนก่อสร้าง * พื้นที่
    ปีฟื้นฟูสุดท้าย = 0
    
    for ฟื้นฟู in ทางเลือก.แผนฟื้นฟูสภาพ:
        if ฟื้นฟู.ปีดำเนินการ <= ระยะวิเคราะห์:
            ต้นทุน = ฟื้นฟู.ต้นทุนต่อหน่วย * พื้นที่
            pwf = (1 + อัตราคิดลด) ** (-ฟื้นฟู.ปีดำเนินการ)
            รายการ.append({
                'ปี': ฟื้นฟู.ปีดำเนินการ,
                'กิจกรรม': ฟื้นฟู.ชื่อกิจกรรม,
                'ประเภท': 'ฟื้นฟูสภาพ',
                'ต้นทุนตามปี': ต้นทุน,
                'ตัวคูณ_PW': pwf,
                'มูลค่าปัจจุบัน': ต้นทุน * pwf
            })
            ต้นทุนฟื้นฟูสุดท้าย = ต้นทุน
            ปีฟื้นฟูสุดท้าย = ฟื้นฟู.ปีดำเนินการ
    
    # มูลค่าซาก (ค่าติดลบ = เครดิต)
    if รวมมูลค่าซาก:
        อายุที่คาดหวัง = 15 if 'Flexible' in ทางเลือก.ประเภท or 'ยืดหยุ่น' in ทางเลือก.ประเภท else 20
        sv = คำนวณมูลค่าซาก(
            ต้นทุนฟื้นฟูสุดท้าย, ปีฟื้นฟูสุดท้าย, อายุที่คาดหวัง,
            ระยะวิเคราะห์, ทางเลือก.ร้อยละมูลค่าซาก
        )
        pwf = (1 + อัตราคิดลด) ** (-ระยะวิเคราะห์)
        รายการ.append({
            'ปี': ระยะวิเคราะห์,
            'กิจกรรม': 'มูลค่าซาก',
            'ประเภท': 'มูลค่าซาก',
            'ต้นทุนตามปี': -sv,
            'ตัวคูณ_PW': pwf,
            'มูลค่าปัจจุบัน': -sv * pwf
        })
    
    df = pd.DataFrame(รายการ)
    df = df.sort_values(['ปี', 'กิจกรรม']).reset_index(drop=True)
    
    return df


