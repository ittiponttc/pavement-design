                ผลรอบบำรุง_display = ผลรอบบำรุง.copy()
                ผลรอบบำรุง_display['มูลค่าปัจจุบัน'] = ผลรอบบำรุง_display['มูลค่าปัจจุบัน'].apply(lambda x: f"{x:,.0f}")
                ผลรอบบำรุง_display['ต้นทุนเฉลี่ยรายปี'] = ผลรอบบำรุง_display['ต้นทุนเฉลี่ยรายปี'].apply(lambda x: f"{x:,.0f}")
                ผลรอบบำรุง_display.columns = ['รอบ (ปี)', 'จำนวนครั้ง', 'มูลค่าปัจจุบัน (บาท)', 'EAC (บาท/ปี)']
