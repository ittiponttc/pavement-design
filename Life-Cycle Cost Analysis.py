def คำนวณมูลค่าปัจจุบัน(ต้นทุน: float, ปี: int, อัตราคิดลด: float) -> float:
    """
    คำนวณมูลค่าปัจจุบัน (Present Worth) ของต้นทุนในอนาคต
    
    สูตร: PW = FV × (1 + i)^(-n)
    
    Parameters:
        ต้นทุน: จำนวนเงินในอนาคต (บาท)
        ปี: จำนวนปีจากปัจจุบัน
        อัตราคิดลด: อัตราคิดลดรายปี (ทศนิยม เช่น 0.04 = 4%)
    
    Returns:
        มูลค่าปัจจุบันของต้นทุน (บาท)
    
    หมายเหตุทางวิศวกรรม:
        - ใช้ Real Discount Rate (ไม่รวมเงินเฟ้อ)
        - อัตราคิดลดทั่วไป: 3-7% ขึ้นกับนโยบายหน่วยงาน
        - FHWA แนะนำ 4% สำหรับโครงการของรัฐ
    """
    if ปี < 0:
        raise ValueError(f"ปีต้องไม่ติดลบ ค่าที่ได้รับ: {ปี}")
    if อัตราคิดลด < 0:
        raise ValueError(f"อัตราคิดลดต้องไม่ติดลบ ค่าที่ได้รับ: {อัตราคิดลด}")
    
    # ตัวคูณมูลค่าปัจจุบัน (Present Worth Factor)
    pwf = (1 + อัตราคิดลด) ** (-ปี)
    return ต้นทุน * pwf


def คำนวณมูลค่าปัจจุบันรวม(ตารางต้นทุน: Dict[int, float], อัตราคิดลด: float) -> float:
    """
    คำนวณมูลค่าปัจจุบันรวมจากตารางต้นทุน
    
    Parameters:
        ตารางต้นทุน: Dictionary {ปี: ต้นทุน}
        อัตราคิดลด: อัตราคิดลดรายปี
    
    Returns:
        มูลค่าปัจจุบันรวมของต้นทุนทั้งหมด
    """
    รวม_pw = 0.0
    for ปี, ต้นทุน in ตารางต้นทุน.items():
        รวม_pw += คำนวณมูลค่าปัจจุบัน(ต้นทุน, ปี, อัตราคิดลด)
    return รวม_pw


def คำนวณต้นทุนเฉลี่ยรายปี(pw: float, อัตราคิดลด: float, ระยะวิเคราะห์: int) -> float:
    """
    แปลงมูลค่าปัจจุบันเป็นต้นทุนเฉลี่ยรายปี (Equivalent Annual Cost)
    
    สูตร: EAC = PW × [i(1+i)^N] / [(1+i)^N - 1]
    (Capital Recovery Factor - CRF)
    
    Parameters:
        pw: มูลค่าปัจจุบันรวม
        อัตราคิดลด: อัตราคิดลดรายปี
        ระยะวิเคราะห์: ระยะเวลาวิเคราะห์ (ปี)
    
    Returns:
        ต้นทุนเฉลี่ยรายปี (บาท/ปี)
    
    หมายเหตุทางวิศวกรรม:
        EAC เหมาะสำหรับเปรียบเทียบทางเลือกที่มีอายุใช้งานต่างกัน
    """
    if ระยะวิเคราะห์ <= 0:
        raise ValueError(f"ระยะวิเคราะห์ต้องเป็นบวก ค่าที่ได้รับ: {ระยะวิเคราะห์}")
    if อัตราคิดลด <= 0:
        raise ValueError(f"อัตราคิดลดต้องเป็นบวกสำหรับการคำนวณ EAC")
    
    # Capital Recovery Factor (CRF)
    ตัวเศษ = อัตราคิดลด * (1 + อัตราคิดลด) ** ระยะวิเคราะห์
    ตัวส่วน = (1 + อัตราคิดลด) ** ระยะวิเคราะห์ - 1
    crf = ตัวเศษ / ตัวส่วน
    
    return pw * crf


def คำนวณมูลค่าซาก(
    ต้นทุนฟื้นฟูครั้งสุดท้าย: float,
    ปีฟื้นฟูครั้งสุดท้าย: int,
    อายุใช้งานที่คาดหวัง: int,
    ระยะวิเคราะห์: int,
    ร้อยละมูลค่าซาก: float = 20.0
) -> float:
    """
    คำนวณมูลค่าซากโดยวิธี Straight-Line Depreciation
    
    Parameters:
        ต้นทุนฟื้นฟูครั้งสุดท้าย: ต้นทุนฟื้นฟูครั้งล่าสุด
        ปีฟื้นฟูครั้งสุดท้าย: ปีที่ทำการฟื้นฟูครั้งล่าสุด
        อายุใช้งานที่คาดหวัง: อายุใช้งานที่คาดหวังหลังฟื้นฟู
        ระยะวิเคราะห์: สิ้นสุดระยะวิเคราะห์
        ร้อยละมูลค่าซาก: มูลค่าซากขั้นต่ำเป็น %
    
    Returns:
        มูลค่าซาก (เป็นค่าบวก)
    """
    อายุใช้งานที่เหลือ = อายุใช้งานที่คาดหวัง - (ระยะวิเคราะห์ - ปีฟื้นฟูครั้งสุดท้าย)
    
    if อายุใช้งานที่เหลือ <= 0:
        return ต้นทุนฟื้นฟูครั้งสุดท้าย * (ร้อยละมูลค่าซาก / 100.0)
    
    # Straight-line depreciation
    ค่าเสื่อมต่อปี = ต้นทุนฟื้นฟูครั้งสุดท้าย * (1 - ร้อยละมูลค่าซาก/100.0) / อายุใช้งานที่คาดหวัง
    มูลค่าซาก = ต้นทุนฟื้นฟูครั้งสุดท้าย - ค่าเสื่อมต่อปี * (ระยะวิเคราะห์ - ปีฟื้นฟูครั้งสุดท้าย)
    
    return max(มูลค่าซาก, ต้นทุนฟื้นฟูครั้งสุดท้าย * ร้อยละมูลค่าซาก / 100.0)


