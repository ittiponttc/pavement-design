def วิเคราะห์ความไว_อัตราคิดลด(
    ทางเลือกทั้งหมด: List[ทางเลือกผิวทาง],
    ระยะวิเคราะห์: int,
    อัตราฐาน: float,
    ช่วงการเปลี่ยนแปลง: float = 0.02,
    จำนวนจุด: int = 5
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """
    วิเคราะห์ความไวต่ออัตราคิดลด
    
    Parameters:
        ทางเลือกทั้งหมด: รายการทางเลือก
        ระยะวิเคราะห์: ระยะเวลาวิเคราะห์
        อัตราฐาน: อัตราคิดลดฐาน
        ช่วงการเปลี่ยนแปลง: ช่วง ±
        จำนวนจุด: จำนวนจุดที่ทดสอบ
    
    Returns:
        DataFrame ผลการวิเคราะห์, DataFrame แบบ Pivot
    """
    อัตราทดสอบ = np.linspace(อัตราฐาน - ช่วงการเปลี่ยนแปลง, 
                              อัตราฐาน + ช่วงการเปลี่ยนแปลง, จำนวนจุด)
    ผลลัพธ์ = []
    
    for อัตรา in อัตราทดสอบ:
        for ทางเลือก in ทางเลือกทั้งหมด:
            cf = สร้างตารางกระแสเงินสด(ทางเลือก, ระยะวิเคราะห์, อัตรา)
            pw = cf['มูลค่าปัจจุบัน'].sum()
            ผลลัพธ์.append({
                'อัตราคิดลด': อัตรา,
                'อัตราคิดลด_%': f"{อัตรา*100:.1f}%",
                'ทางเลือก': ทางเลือก.ชื่อ,
                'มูลค่าปัจจุบัน': pw,
                'ต้นทุนเฉลี่ยรายปี': คำนวณต้นทุนเฉลี่ยรายปี(pw, อัตรา, ระยะวิเคราะห์)
            })
    
    df = pd.DataFrame(ผลลัพธ์)
    pivot = df.pivot(index='อัตราคิดลด_%', columns='ทางเลือก', values='มูลค่าปัจจุบัน')
    
    return df, pivot


def วิเคราะห์ความไว_รอบบำรุงรักษา(
    ทางเลือก: ทางเลือกผิวทาง,
    ระยะวิเคราะห์: int,
    อัตราคิดลด: float,
    ชื่อกิจกรรม: str,
    ช่วงรอบ: List[int]
) -> pd.DataFrame:
    """
    วิเคราะห์ความไวต่อรอบการบำรุงรักษา
    """
    ผลลัพธ์ = []
    
    for รอบ in ช่วงรอบ:
        # สร้างแผนบำรุงรักษาที่แก้ไข
        แผนใหม่ = []
        for บำรุง in ทางเลือก.แผนบำรุงรักษา:
            if บำรุง.ชื่อกิจกรรม == ชื่อกิจกรรม:
                แผนใหม่.append(กิจกรรมบำรุงรักษา(
                    ชื่อกิจกรรม=บำรุง.ชื่อกิจกรรม,
                    ต้นทุนต่อหน่วย=บำรุง.ต้นทุนต่อหน่วย,
                    ปีเริ่มต้น=บำรุง.ปีเริ่มต้น,
                    ความถี่=รอบ
                ))
            else:
                แผนใหม่.append(บำรุง)
        
        ทางเลือกชั่วคราว = ทางเลือกผิวทาง(
            ชื่อ=ทางเลือก.ชื่อ,
            ประเภท=ทางเลือก.ประเภท,
            ต้นทุนก่อสร้าง=ทางเลือก.ต้นทุนก่อสร้าง,
            แผนบำรุงรักษา=แผนใหม่,
            แผนฟื้นฟูสภาพ=ทางเลือก.แผนฟื้นฟูสภาพ,
            ร้อยละมูลค่าซาก=ทางเลือก.ร้อยละมูลค่าซาก,
            พื้นที่=ทางเลือก.พื้นที่
        )
        
        cf = สร้างตารางกระแสเงินสด(ทางเลือกชั่วคราว, ระยะวิเคราะห์, อัตราคิดลด)
        pw = cf['มูลค่าปัจจุบัน'].sum()
        จำนวนครั้ง = len(cf[cf['กิจกรรม'] == ชื่อกิจกรรม])
        
        ผลลัพธ์.append({
            'รอบ_ปี': รอบ,
            'จำนวนครั้ง': จำนวนครั้ง,
            'มูลค่าปัจจุบัน': pw,
            'ต้นทุนเฉลี่ยรายปี': คำนวณต้นทุนเฉลี่ยรายปี(pw, อัตราคิดลด, ระยะวิเคราะห์)
        })
    
    return pd.DataFrame(ผลลัพธ์)


